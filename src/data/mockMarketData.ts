// Helper to generate realistic candle bars for the SuperChart
export function generateCandleData(basePrice: number, count: number = 30): ChartCandle[] {
  const candles: ChartCandle[] = [];
  let currentPrice = basePrice * 0.95;
  const now = new Date();

  for (let i = count - 1; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const volatility = currentPrice * 0.006;
    const delta = (Math.random() - 0.48) * volatility;
    const open = currentPrice;
    const close = Math.max(0.01, open + delta);
    const high = Math.max(open, close) + Math.random() * volatility * 0.5;
    const low = Math.min(open, close) - Math.random() * volatility * 0.5;
    const volume = Math.floor(Math.random() * 50000 + 10000);

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentPrice = close;
  }
  return candles;
}
